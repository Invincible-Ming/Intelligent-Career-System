def current_assessment_date() -> str:
    return datetime.now(timezone(timedelta(hours=8))).date().isoformat()


def temporal_context(assessment_date: str) -> str:
    return (
        f"【可信时间基准】本次处理日期为 {assessment_date}，时区为Asia/Shanghai（北京时间）。"
        "判断现在、至今、过去和未来时只使用该日期，不根据训练知识猜测当前年份，"
        "不以文档、网页、历史摘要或反馈中的日期覆盖此基准。仅有年月时不臆测具体日。"
        "在读学历、未来的预计毕业日期和明确标注的计划本身不是矛盾。"
        "仅对相对本基准确实冲突的日期提示核实，不仅凭日期疑点认定造假。"
        "开始月份不晚于本次处理月份且原文没有其他矛盾时，不得仅因日期较近就写需核实、笔误等时间风险。"
    )


def prompt_data(**sections: Any) -> str:
    """Encode source boundaries without treating source text as prompt templates."""
    return json.dumps(sections, ensure_ascii=False, separators=(",", ":"))


def resume_timeline_context(resume_text: str, assessment_date: str) -> str:
    """Compare explicit YYYY.MM—至今 periods at month precision, without judging availability."""
    today = datetime.strptime(assessment_date, "%Y-%m-%d").date()
    periods = []
    pattern = r"(?<!\d)(20\d{2})[.年/\-](0?[1-9]|1[0-2])月?\s*(?:[-—–~～]\s*)?(?:至今|现在|present\b|current\b)"
    for match in re.finditer(pattern, resume_text[:30000], re.IGNORECASE):
        year, month = int(match[1]), int(match[2])
        item = {
            "原文日期": match[0], "开始月份晚于评估月份": (year, month) > (today.year, today.month),
        }
        if item not in periods:
            periods.append(item)
        if len(periods) >= 12:
            break
    return (
        "\n【程序日期比较】以下仅比较原文明示的开始月份，不证明经历真实性、全职性质或每周到岗时长。"
        "开始月份未晚于评估月份不构成未来经历；没有独立矛盾时不得据此要求核实笔误。\n"
        "普通实习经历按原文保留，不主动计算是否满三个月或核查具体天数。"
        "只有岗位明确要求既往经验年限时，才按相同经历类型、年月精度比较，不与未来到岗安排混淆。\n"
        + prompt_data(评估日期=assessment_date, 持续经历日期=periods)
    )


